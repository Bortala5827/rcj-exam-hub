  function pick() {
    return TOPICS[Math.floor(Math.random() * TOPICS.length)];
  }

  // 按 category 随机抽一题（不重复上次）
  function pickByCat(cat, exclude) {
    var pool = TOPICS.filter(function (t) { return t.c === cat && (!exclude || t.q !== exclude); });
    if (!pool.length) return pick();
    return pool[Math.floor(Math.random() * pool.length)];
  }

  // 抽 N 个不同分类的题（用于"今日掉落"）
  function pickDaily(cats) {
    return cats.map(function (c) { return pickByCat(c); });
  }

  // 随机抽 N 个不同分类
  function randomCats(n) {
    var all = Object.keys(CAT_LABEL);
    var out = [];
    while (out.length < n && all.length) {
      var i = Math.floor(Math.random() * all.length);
      out.push(all.splice(i, 1)[0]);
    }
    return out;
  }

